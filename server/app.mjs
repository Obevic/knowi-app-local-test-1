function seededRandom(seed) {
  let s = seed >>> 0;
  return function () {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function generateItems() {
  const rand = seededRandom(20261103);
  const items = [];
  const seen = new Set();
  const target = 120;
  let guard = 0;
  while (items.length < target && guard < 5000) {
    guard++;
    const name = ITEM_NAMES[Math.floor(rand() * ITEM_NAMES.length)];
    if (seen.has(name)) continue;
    seen.add(name);
    const supplier = SUPPLIERS[Math.floor(rand() * SUPPLIERS.length)];
    const category = CATEGORIES[Math.floor(rand() * CATEGORIES.length)];
    const quantity = Math.floor(rand() * 400) + 1;
    const reorderPoint = Math.floor(rand() * 60) + 5;
    const unitCost = Math.round((rand() * 240 + 1.5) * 100) / 100;
    items.push({
      id: items.length + 1,
      name,
      supplier,
      category,
      quantity,
      reorderPoint,
      unitCost,
    });
  }
  return items;
}

const ITEMS = generateItems();

app.get('/api/items', (req, res) => {
  res.json({ items: ITEMS });
});

app.use(express.static(webRoot));
app.use((req, res, next) => {
  if (req.method !== 'GET' && req.method !== 'HEAD') return next();
  if (req.path.startsWith('/api/')) return res.status(404).json({ error: 'Not found' });
  res.sendFile(indexHtmlPath);
});

